"""DOCX to PDF converter using LibreOffice headless."""

import asyncio
import logging
import subprocess
import tempfile
from pathlib import Path
from typing import Optional

logger = logging.getLogger(__name__)


class DocxToPdfConverter:
    """Конвертирует DOCX в PDF через LibreOffice."""

    def __init__(self, libreoffice_path: Optional[str] = None):
        """
        Инициализирует конвертер.

        Args:
            libreoffice_path: Путь к исполняемому файлу LibreOffice.
                             Если None, используется 'libreoffice' из PATH.
        """
        self.libreoffice_path = libreoffice_path or "libreoffice"

    async def convert(self, docx_bytes: bytes) -> bytes:
        """
        Конвертирует DOCX в PDF.

        Args:
            docx_bytes: Содержимое DOCX файла в виде байтов.

        Returns:
            Содержимое PDF файла в виде байтов.

        Raises:
            RuntimeError: Если конвертация не удалась.
        """
        # Создаём временные файлы для конвертации
        with tempfile.TemporaryDirectory() as tmpdir:
            tmpdir_path = Path(tmpdir)

            # Записываем DOCX
            docx_path = tmpdir_path / "input.docx"
            docx_path.write_bytes(docx_bytes)

            # Конвертируем через LibreOffice
            pdf_path = await asyncio.to_thread(
                self._convert_via_libreoffice,
                docx_path,
                tmpdir_path
            )

            # Читаем результат
            return pdf_path.read_bytes()
        
    def _convert_via_libreoffice(self, docx_path: Path, output_dir: Path) -> Path:
        """
        Выполняет конвертацию DOCX → PDF через LibreOffice headless.

        Args:
            docx_path: Путь к входному DOCX файлу.
            output_dir: Директория для выходного PDF файла.

        Returns:
            Путь к созданному PDF файлу.
        """
        cmd = [
            self.libreoffice_path,
            "--headless",
            "--convert-to", "pdf",
            "--outdir", str(output_dir),
            str(docx_path)
        ]

        logger.info(f"Converting DOCX to PDF via LibreOffice: {' '.join(cmd)}")

        try:
            result = subprocess.run(
                cmd,
                capture_output=True,
                text=True,
                cwd=str(output_dir),
                timeout=120  # максимум 2 минуты на конвертацию
            )

            if result.returncode != 0:
                error_msg = result.stderr.strip() or result.stdout.strip()
                raise RuntimeError(f"LibreOffice conversion failed: {error_msg}")

            # Ищем созданный PDF файл
            pdf_files = list(output_dir.glob("*.pdf"))
            if not pdf_files:
                raise RuntimeError("No PDF file generated by LibreOffice")

            return pdf_files[0]

        except subprocess.TimeoutExpired:
            raise RuntimeError("LibreOffice conversion timed out (2 min)")
        except FileNotFoundError:
            raise RuntimeError(
                "LibreOffice not found. Install it or specify libreoffice_path."
            )


# Глобальный экземпляр конвертера
docx_to_pdf_converter = DocxToPdfConverter()
